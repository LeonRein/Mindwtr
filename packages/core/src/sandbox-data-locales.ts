type ContentLocale = 'en' | 'de' | 'fr' | 'es' | 'ru' | 'zh' | 'zh-Hant';
type TupleKeys<T extends readonly string[]> = T[number];
type ContentMap<T extends readonly string[]> = Record<TupleKeys<T>, string>;

export type SandboxContent = {
    areas: ContentMap<typeof AREA_KEYS>;
    projects: ContentMap<typeof PROJECT_KEYS>;
    sections: ContentMap<typeof SECTION_KEYS>;
    people: ContentMap<typeof PERSON_KEYS>;
    personNotes: ContentMap<typeof PERSON_KEYS>;
    tasks: ContentMap<typeof TASK_KEYS>;
    tags: ContentMap<typeof TAG_KEYS>;
    contexts: ContentMap<typeof CONTEXT_KEYS>;
    text: ContentMap<typeof TEXT_KEYS>;
    checklist: ContentMap<typeof CHECKLIST_KEYS>;
};

const toMap = <T extends readonly string[]>(keys: T, values: StringTuple<T>): ContentMap<T> =>
    Object.fromEntries(keys.map((key, index) => [key, values[index]])) as ContentMap<T>;

const hydrate = (bundle: ContentBundle): SandboxContent => ({
    areas: toMap(AREA_KEYS, bundle.areas),
    projects: toMap(PROJECT_KEYS, bundle.projects),
    sections: toMap(SECTION_KEYS, bundle.sections),
    people: toMap(PERSON_KEYS, bundle.people),
    personNotes: toMap(PERSON_KEYS, bundle.personNotes),
    tasks: toMap(TASK_KEYS, bundle.tasks),
    tags: toMap(TAG_KEYS, bundle.tags),
    contexts: toMap(CONTEXT_KEYS, bundle.contexts),
    text: toMap(TEXT_KEYS, bundle.text),
    checklist: toMap(CHECKLIST_KEYS, bundle.checklist),
});

const CONTENT: Record<ContentLocale, SandboxContent> = {
    en: hydrate(en),
    de: hydrate(de),
    fr: hydrate(fr),
    es: hydrate(es),
    ru: hydrate(ru),
    zh: hydrate(zh),
    'zh-Hant': hydrate(zhHant),
};

const resolveContentLocale = (language: string | undefined): ContentLocale => {
    if (language === 'de' || language === 'fr' || language === 'es' || language === 'ru') return language;
    if (language === 'zh-Hant') return 'zh-Hant';
    if (language === 'zh' || language === 'zh-Hans') return 'zh';
    return 'en';
};

export const getSandboxContent = (language: string | undefined): SandboxContent =>
    CONTENT[resolveContentLocale(language)];
